# 0x8004CF3B: and rsp, -0x10
# 0x8004CF3F: call 0x8004cf32   ; <-- CALLS THE PROLOGUE (WRONG!)
# 0x8004CF44: mov rsp, r13      ; epilogue
# 0x8004CF47: pop r13
# 0x8004CF49: and [rbp-8], 0    ; <-- actual function body starts here
# 
# So the call at 0x4CF3F should target 0x4CF49 (the body), not 0x4CF32 (the wrapper).
# The correct rel32 would be: 0x4CF49 - 0x4CF44 = 5
# But actual rel32 = 0xFFFFFFEE = -18, so target = 0x4CF44 + (-18) = 0x4CF32

